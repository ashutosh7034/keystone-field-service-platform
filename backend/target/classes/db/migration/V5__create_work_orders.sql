CREATE TABLE work_orders (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    work_order_code VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    priority VARCHAR(50) NOT NULL DEFAULT 'MEDIUM',
    status VARCHAR(50) NOT NULL DEFAULT 'NEW',
    customer_id BIGINT NOT NULL,
    site_id BIGINT NOT NULL,
    assigned_technician_id BIGINT NULL,
    created_by_user_id BIGINT NOT NULL,
    sla_due_date DATETIME NOT NULL,
    sla_status VARCHAR(50) NOT NULL DEFAULT 'ON_TRACK',
    internal_notes TEXT,
    cancellation_reason VARCHAR(255),
    completed_at DATETIME NULL,
    closed_at DATETIME NULL,
    cancelled_at DATETIME NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_wo_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
    CONSTRAINT fk_wo_site FOREIGN KEY (site_id) REFERENCES sites(id),
    CONSTRAINT fk_wo_technician FOREIGN KEY (assigned_technician_id) REFERENCES users(id),
    CONSTRAINT fk_wo_creator FOREIGN KEY (created_by_user_id) REFERENCES users(id),
    INDEX idx_wo_code (work_order_code),
    INDEX idx_wo_status (status),
    INDEX idx_wo_priority (priority),
    INDEX idx_wo_customer (customer_id),
    INDEX idx_wo_site (site_id),
    INDEX idx_wo_technician (assigned_technician_id),
    INDEX idx_wo_sla_status (sla_status),
    INDEX idx_wo_sla_due (sla_due_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
